"""`frontend/lib/routes.ts`, for bin/types: a function per named page route, so the frontend names a page as Django does
(D121, in place of WISP 3's Rails route helpers). Paths come from Django's own reverse table, so `path()` converters
and `re_path()` groups both work, and each function encodes its parameters as `reverse()` would."""

from collections.abc import Iterable, Iterator
from dataclasses import dataclass

from django.core.management.base import BaseCommand, CommandError
from django.urls import URLPattern, URLResolver, get_resolver
from django.urls.converters import IntConverter

# The apps whose named routes are pages (or files) a page links to; the API (its own client, lib/api.ts), the admin
# and Django's redirects are left out
PAGE_APPS = ("web", "updates", "ops")


@dataclass(frozen=True, kw_only=True)
class Route:
    name: str  # Django's URL name
    template: str  # the path with `%(param)s` for each parameter, as Django's reverse table holds it
    params: tuple[tuple[str, str], ...]  # each parameter and its TypeScript type


def _patterns(resolver: URLResolver) -> Iterator[URLPattern]:
    """Every pattern reachable without a namespace (a namespaced include is another app's: the API's, the admin's)."""
    for entry in resolver.url_patterns:
        if isinstance(entry, URLResolver):
            if entry.namespace is None:
                yield from _patterns(entry)
        elif isinstance(entry, URLPattern):
            yield entry


def _app_of(pattern: URLPattern) -> str:
    callback = pattern.callback
    view_class = getattr(callback, "view_class", None)
    module = (view_class or callback).__module__ or ""
    return module.split(".")[0]


def page_routes(resolver: URLResolver | None = None, apps: Iterable[str] = PAGE_APPS) -> list[Route]:
    """The named routes of `apps`' views, by name."""
    resolver = resolver or get_resolver()
    apps = tuple(apps)
    names = sorted({p.name for p in _patterns(resolver) if p.name and _app_of(p) in apps})
    routes = []
    for name in names:
        possibilities = resolver.reverse_dict.getlist(name)
        if len(possibilities) != 1 or len(possibilities[0][0]) != 1:
            raise CommandError(
                f"The URL name {name!r} has more than one pattern; give each its own name for routes.ts."
            )
        (template, params), _pattern, _defaults, converters = possibilities[0][0][0], *possibilities[0][1:]
        types = tuple(
            (param, "number" if isinstance(converters.get(param), IntConverter) else "string") for param in params
        )
        routes.append(Route(name=name, template=template, params=types))
    return routes


def _identifier(name: str) -> str:
    """`changelog-feed` as `changelogFeed`."""
    head, *rest = name.replace("_", "-").split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def _function(route: Route) -> str:
    path = "/" + route.template
    shown = path
    body = path.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    for param, _type in route.params:
        shown = shown.replace(f"%({param})s", f"<{param}>")
        body = body.replace(f"%({param})s", f"${{part(params.{param})}}")
    shown, body, path = (text.replace("%%", "%") for text in (shown, body, path))
    if route.params:
        fields = "; ".join(f"{param}: {kind}" for param, kind in route.params)
        signature, text = f"(params: {{ {fields} }})", f"`{body}`"
    else:
        signature, text = "()", "'" + path.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return f"  /** {route.name}: {shown} */\n  {_identifier(route.name)}: {signature}: string => {text},\n"


def routes_ts(routes: list[Route]) -> str:
    seen: dict[str, str] = {}
    for route in routes:
        other = seen.setdefault(_identifier(route.name), route.name)
        if other != route.name:
            raise CommandError(f"The URL names {other!r} and {route.name!r} give the same function name in routes.ts.")
    needs_part = any(route.params for route in routes)
    lines = [
        "// Generated by bin/types from Django's URL names (web.management.commands.export_routes). Don't edit.",
        "// A function per page route, so a link names its page as Django does: routes.changelog() is '/changelog'.",
        "",
    ]
    if needs_part:
        lines += [
            "// A parameter encoded as Django's reverse() does: everything but / : @ and RFC 3986's sub-delimiters",
            "function part(value: string | number): string {",
            "  return encodeURIComponent(String(value)).replace(/%(2F|3A|40|24|26|2B|2C|3B|3D)/gi, decodeURIComponent)",
            "}",
            "",
        ]
    lines.append("export const routes = {")
    text = "\n".join(lines) + "\n" + "".join(_function(route) for route in routes) + "}\n"
    return text


class Command(BaseCommand):
    help = "Print frontend/lib/routes.ts (a function per named page route), for bin/types"

    def handle(self, *args, **options):
        self.stdout.write(routes_ts(page_routes()), ending="")
