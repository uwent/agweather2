import { describe, expect, it } from 'vitest'

import { routes } from './routes'

describe('routes (generated by bin/types)', () => {
  it('gives each page its path', () => {
    expect(routes.home()).toBe('/')
    expect(routes.changelog()).toBe('/changelog')
    expect(routes.apiUse()).toBe('/api-use')
  })

  it('encodes parameters as Django’s reverse() does (web/tests/test_routes.py)', () => {
    expect(routes.downloads({ path: 'daily/2025/a b+c,d#e?.nc' })).toBe('/downloads/daily/2025/a%20b+c,d%23e%3F.nc')
  })
})
