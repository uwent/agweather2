// Compiles a JSON Schema from `manage.py export_types` (the page props, or with --api the API's) into TypeScript;
// run by bin/types. Arguments: input, output, the root's title, and what the types come from (for the banner).
import { readFileSync, writeFileSync } from 'node:fs'
import { compile } from 'json-schema-to-typescript'

const [input, output, root = 'PageProps', source = 'the Pydantic props in app/*/props.py'] = process.argv.slice(2)
const schema = JSON.parse(readFileSync(input, 'utf8'))

// Pydantic titles every field, which json2ts would turn into an alias type each ("type Version = string")
for (const definition of Object.values(schema.$defs ?? {})) {
  for (const property of Object.values(definition.properties ?? {})) delete property.title
}

const ts = await compile(schema, root, {
  bannerComment: `// Generated by bin/types from ${source}. Don't edit.`,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { semi: false, singleQuote: true, printWidth: 120 },
})

// Drop the root listing (it only keeps every definition reachable) and json2ts's provenance comments
const cleaned = ts
  .replace(new RegExp(`export interface ${root} \\{[\\s\\S]*?\\n\\}\\n`), '')
  .replace(/\/\*\*\n \* This interface was referenced by[\s\S]*?\*\/\n/g, '')
  .replace(/ \*\n \* This interface was referenced by[\s\S]*?(?= \*\/\n)/g, '')
writeFileSync(output, cleaned)
