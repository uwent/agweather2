"""Writes `agmodels/names.py`: the catalog's daily variables, running totals and units as `Literal` types.

agmodels can't import agdata (agdata depends on it), so the names a model spec uses are typed from this generated
copy, and pyright flags a name the catalog doesn't have where it's written. `bin/types` runs it; CI and
`test_names_are_current` fail when it's stale.

    uv run python scripts/generate_names.py [--check]
"""

import argparse
import sys
from pathlib import Path

from agdata.catalog import CUMULATIVE_VARIABLES, DAILY_VARIABLES
from agdata.units import UNITS

TARGET = Path(__file__).resolve().parents[1] / "packages/agmodels/src/agmodels/names.py"


def render() -> str:
    def literal(type_name: str, doc: str, names) -> str:
        body = "".join(f'    "{n}",\n' for n in sorted(names))
        return f"# {doc}\n{type_name} = Literal[\n{body}]\n"

    return (
        '"""The catalog\'s names as types, for model specs (generated by `scripts/generate_names.py` from\n'
        '`agdata.catalog` and `agdata.units`; run `bin/types` after changing either, and commit the result)."""\n\n'
        "from typing import Literal\n\n"
        + literal("DailyName", "Daily variables and features (`DAILY_VARIABLES`): a model's inputs", DAILY_VARIABLES)
        + "\n"
        + literal("CumulativeName", "Running totals from January 1 (`CUMULATIVE_VARIABLES`)", CUMULATIVE_VARIABLES)
        + "\n"
        + literal("UnitSymbol", "Units (`agdata.units.UNITS`)", UNITS)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale instead of writing it")
    text = render()
    if parser.parse_args().check:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is stale: run bin/types", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(Path.cwd()) if TARGET.is_relative_to(Path.cwd()) else TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
