"""v1's `dd_table` caller against v2 (PLAN.md Phase 5 C): the Waunakee lawn notifier's query.

uv run python scripts/compare_v1_dd_table.py --start 2026-01-01 --end 2026-10-31 [--out docs/validation-v1-dd-table.md]

The old server's log (2026-10-19 to 11-02) has it twice a day at one point:

    /api/degree_days/dd_table?lat=43.18&lng=-89.45&models=dd_50_86,dd_32
    /api/precips?lat=43.18&lng=-89.45&start_date=<30 days back>&end_date=<yesterday>

v1's `dd_50_86` is single sine 50/86 °F and `dd_32` single sine from 32 °F with no upper threshold
(`Weather#degree_days`' default upper of 150 °F), so in v2 they are `dd=sine_50_86,sine_32` on `/degree-days`
(daily values and running totals, as `dd_table` gives) and the precip is `/weather/totals` or `/weather/daily`.
v1 is asked with explicit dates (its defaults are January 1 to its latest import) so the cache in tmp/v1-cache
stays valid. v1 is a reference, not the truth (D54). `--quiet` prints only warnings, failures and the summary.
"""

import argparse
import os
import sys
from datetime import date, timedelta
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "app"))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
os.environ.setdefault("DJANGO_ENV", "development")

import django  # noqa: E402

django.setup()

from django.test import Client  # noqa: E402

from agdata.clients.agweather_v1 import AgWeatherV1  # noqa: E402
from agdata.progress import Reporter  # noqa: E402

LAT, LNG = 43.18, -89.45  # the lawn notifier's point (Waunakee)
SETTINGS = [("dd_50_86", "sine_50_86"), ("dd_32", "sine_32")]  # (v1 column, v2 setting)
RAIN_DAYS = 30  # the notifier's precip window, ending on the last day


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--start", required=True)
    parser.add_argument("--end", required=True, help="last day, inclusive")
    parser.add_argument("--out", default="docs/validation-v1-dd-table.md")
    parser.add_argument("--quiet", action="store_true", help="print only warnings, failures and the summary")
    args = parser.parse_args()
    report = Reporter(quiet=args.quiet)
    try:
        first, last = date.fromisoformat(args.start), date.fromisoformat(args.end)
    except ValueError as error:
        parser.error(f"--start and --end must be YYYY-MM-DD dates: {error}")
    if first > last:
        parser.error("--start must not be after --end")
    old = AgWeatherV1(cache_dir=REPO / "tmp/v1-cache")
    v2 = Client(HTTP_HOST="localhost")
    report.step(f"the lawn notifier's point ({LAT}, {LNG}), {first} to {last}")

    try:
        v1 = old.point(
            "degree_days/dd_table",
            lat=LAT,
            lng=LNG,
            models=",".join(s[0] for s in SETTINGS),
            start_date=str(first),
            end_date=str(last),
        )
    except Exception as error:  # production server: report, don't crash
        report.fail("v1 dd_table", error)
        report.finish()
        return 1
    v2_dd = v2.get(
        "/api/v2/degree-days",
        {"lat": LAT, "lng": LNG, "dd": ",".join(s[1] for s in SETTINGS), "start": first, "end": last},
    ).json()
    if "errors" in v2_dd:
        report.fail("v2 degree days", str(v2_dd["errors"]))
        report.finish()
        return 1

    rain_first = last - timedelta(days=RAIN_DAYS - 1)
    try:
        v1_rain = old.point("precips", lat=LAT, lng=LNG, units="mm", start_date=str(rain_first), end_date=str(last))
    except Exception as error:
        report.fail("v1 precips", error)
        report.finish()
        return 1
    v2_rain = v2.get(
        "/api/v2/weather/daily",
        {"lat": LAT, "lng": LNG, "start": rain_first, "end": last, "vars": "precipitation_sum", "units": "metric"},
    ).json()

    text = _report(first, last, rain_first, v1, v2_dd, v1_rain, v2_rain)
    Path(args.out).write_text(text)
    report.step(f"wrote {args.out}")
    return 0 if report.finish("compared the dd_table query") else 1


def _v1_days(v1: dict) -> dict[str, dict]:
    """v1's `data`, keyed by date (`{date: {min_temp, max_temp, <model>: {value, total}}}`)."""
    data = v1["data"]
    return data if isinstance(data, dict) else {row["date"]: row for row in data}


def _report(first, last, rain_first, v1, v2_dd, v1_rain, v2_rain) -> str:
    days = _v1_days(v1)
    d2 = v2_dd["data"]
    v2_days = {day: k for k, day in enumerate(d2["date"])}
    meta = v2_dd["meta"]
    lines = [
        "# v1's `dd_table` caller against v2",
        "",
        f"Generated by `scripts/compare_v1_dd_table.py --start {first} --end {last}` (PLAN.md Phase 5 C) for the",
        "Waunakee lawn notifier's query (old server log, 2026-10-19 to 11-02, twice a day):",
        "`/api/degree_days/dd_table?lat=43.18&lng=-89.45&models=dd_50_86,dd_32` and `/api/precips` over the last",
        "30 days. v1 is a reference, not the truth (D54). v1 reads its 0.1° point (43.2, −89.5, the mean of the",
        f"2.5 km cells around it); v2 reads the cell containing the point ({meta['location']['cell']['lat']}, "
        f"{meta['location']['cell']['lng']}). v2's sources: " + ", ".join(meta["sources"]) + ".",
        "",
        "## In v2",
        "",
        "v1's `dd_50_86` is single sine 50/86 °F and `dd_32` single sine from 32 °F with no upper threshold, so the",
        "query is one request with the same columns (each day's value and the running total per setting, and the",
        "day's minimum and maximum):",
        "",
        "```",
        "/api/v2/degree-days?lat=43.18&lng=-89.45&dd=sine_50_86,sine_32&forecast=false",
        "```",
        "",
        "`forecast=false` keeps v1's end (the last full day); without it, the table runs on through the forecast,",
        "with `kind` marking forecast days. `/degree-days/table` gives the totals alone. The precip is",
        "`/weather/totals?lat=43.18&lng=-89.45&start=…&vars=precipitation_sum` (or `/weather/daily` for each day).",
        "",
        "## Degree days",
        "",
        "Running totals from January 1, °F·d, on the last day both have, and each day's value, v2 − v1:",
        "",
        "| setting | v1 total | v2 total | difference | difference, % | daily mean difference | daily MAE |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    shared = sorted(d for d in days if d in v2_days)
    for v1_name, v2_name in SETTINGS:
        pairs = [
            (days[d][v1_name]["value"], d2[f"dd_{v2_name}"][v2_days[d]])
            for d in shared
            if days[d].get(v1_name) and d2[f"dd_{v2_name}"][v2_days[d]] is not None
        ]
        end = next(
            (d for d in reversed(shared) if days[d].get(v1_name) and d2[f"dd_{v2_name}_cum"][v2_days[d]] is not None),
            None,
        )
        if not pairs or end is None:
            continue
        a, b = np.array(pairs, dtype=float).T
        t1, t2 = days[end][v1_name]["total"], d2[f"dd_{v2_name}_cum"][v2_days[end]]
        lines.append(
            f"| {v1_name} → {v2_name} | {t1:.0f} | {t2:.0f} | {t2 - t1:+.0f} | {100 * (t2 - t1) / t1:+.1f} | "
            f"{(b - a).mean():+.2f} | {np.abs(b - a).mean():.2f} |"
        )
    lows = [
        d2["air_temperature_min"][v2_days[d]] - days[d]["min_temp"]
        for d in shared
        if days[d].get("min_temp") is not None and d2["air_temperature_min"][v2_days[d]] is not None
    ]
    highs = [
        d2["air_temperature_max"][v2_days[d]] - days[d]["max_temp"]
        for d in shared
        if days[d].get("max_temp") is not None and d2["air_temperature_max"][v2_days[d]] is not None
    ]
    v1_missing = sum(1 for d in shared if days[d].get("min_temp") is None)
    summary = meta["summary"]
    lines += [
        "",
        "Daily temperatures behind them, v2 − v1 (°F). v1's day is midnight to midnight Central time, following",
        "daylight saving; v2's is midnight to midnight CST all year (D74), an hour later from March to November,",
        "which accounts for most of the minimum's spread (`validation-v1.md` compares both day bases;",
        "`day_basis=local` gives v1's days):",
        "",
        "| | mean | MAE | 5th–95th percentile |",
        "| --- | --- | --- | --- |",
    ]
    for label, values in (("minimum", np.array(lows)), ("maximum", np.array(highs))):
        if values.size:
            lo, hi = np.percentile(values, [5, 95])
            lines.append(f"| {label} | {values.mean():+.2f} | {np.abs(values).mean():.2f} | {lo:+.1f} to {hi:+.1f} |")
    lines += [
        "",
        f"Days: {len(shared)} in both; v1 without temperatures on {v1_missing} (its running total counts such a day",
        f"as 0, unflagged); v2 missing {summary.get('days_missing', 0)} and estimated "
        f"{summary.get('days_estimated', 0)} (flagged in `temperature_estimated`).",
        "",
        f"## Precipitation, {rain_first} to {last}",
        "",
    ]
    r1 = {row["date"]: row["value"] for row in v1_rain["data"]} if isinstance(v1_rain["data"], list) else {}
    r2 = dict(zip(v2_rain["data"]["date"], v2_rain["data"]["precipitation_sum"], strict=True))
    both = [d for d in r1 if r1[d] is not None and r2.get(d) is not None]
    t1, t2 = sum(r1[d] for d in both), sum(r2[d] for d in both)
    wet1 = sum(r1[d] >= 0.25 for d in both)
    wet2 = sum(r2[d] >= 0.25 for d in both)
    lines += [
        "| | v1 | v2 |",
        "| --- | --- | --- |",
        f"| total, mm | {t1:.1f} | {t2:.1f} |",
        f"| days with ≥ 0.25 mm | {wet1} | {wet2} |",
        f"| days compared | {len(both)} | {len(both)} |",
        "",
        f"v2 missing precipitation days: {sum(v is None for v in r2.values())}.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    sys.exit(main())
